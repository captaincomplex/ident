GW, GH = 5, 7

def blit(img, x, y, s, color):
    for ch in s.upper():
        g = F.get(ch, F[" "])
        for r in range(GH):
            for c in range(GW):
                if g[r][c] == "#":
                    xx, yy = x + c, y + r
                    if 0 <= xx < img.size[0] and 0 <= yy < img.size[1]:
                        img.putpixel((xx, yy), color)
        x += GW + 1
    return x

def width(s):
    return len(s) * (GW + 1) - 1
